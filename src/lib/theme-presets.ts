/**
 * THE HUED PRESETS, generated and measured rather than hand-picked.
 *
 * Each is one hue spent two ways: a saturated `--primary`, and a whisper of the
 * same hue through the neutrals so the greys belong to it rather than sitting
 * beside it. Everything the product calls affirmative or current wears it,
 * which is what makes a preset visible without a swatch to compare against.
 *
 * THREE RULES DECIDED EVERY VALUE:
 *
 * 1. CHROMA IS CLAMPED TO THE sRGB GAMUT PER HUE. Above the ceiling the browser
 *    clips, so the token names one colour and paints another and every ratio
 *    measured from it is measured against something nothing displays.
 *
 * 2. THE 4.5:1 FLOOR LEAVES A HOLE. White text needs a primary around
 *    L <= 0.55; dark text needs L >= 0.62. Nothing legible lives between. Dark
 *    ramps always take a light primary with dark text — what shadcn's own dark
 *    `--primary` does — so every preset agrees with the default about what an
 *    affirmative control weighs.
 *
 * 3. LIGHT RAMPS TAKE A DARK PRIMARY WITH WHITE TEXT, matching Neutral — UNLESS
 *    the hue cannot hold chroma down there (under C 0.14 it is mud, not a hue),
 *    in which case the ramp INVERTS to a light primary with dark text. The
 *    warm-and-green band trips it: Amber at L 0.52 tops out near C 0.11
 *    (brown), Lime near 0.13 (olive), Teal near 0.09 (grey). The inversion is
 *    what makes those three offerable at all — an earlier cut excluded teal
 *    outright, on the mistaken assumption that a light ramp required a dark
 *    primary.
 *
 * WHAT IS STILL DELIBERATELY ABSENT: any hue within about 40 degrees of
 * `--destructive` (27 light / 22 dark) — a primary that reads as the error
 * colour spends the one signal the monochrome default has left; Rose at 345
 * (42 degrees) is the closest, and pink against orange-red survives. And Sky
 * (~225): it lands on the same washed cyan-blue band as Teal and would be the
 * same preset twice.
 *
 * Every ramp below clears the same floors the base does — see
 * `styles.contrast.test.ts`, which ranges over presets rather than over the
 * two shipped ramps alone.
 */

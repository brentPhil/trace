/** The four tokens a swatch draws. tweakcn's preset swatch renders `primary`,
 *  `accent`, `secondary`, `border` (theme-preset-select.tsx, four ColorBoxes),
 *  and this followed it verbatim until the solid-sidebar presets arrived. Now
 *  the last chip is `sidebar` instead of `border`: the rail colour is the
 *  HEADLINE difference between Blue and Midnight, and a swatch without it
 *  shows two identical rows — while border (L 0.92) next to secondary (0.968)
 *  was two chips saying one thing. Still four chips, still tweakcn's shape.
 *
 *  For the tinted presets `sidebar` is a near-white and the swap is invisible;
 *  for the solid-sidebar ones it is the dark block that names them. */
export const SWATCH_TOKENS = ["primary", "accent", "secondary", "sidebar"] as const

export function presetById(id: ThemePresetId): ThemePreset {
  const found = THEME_PRESETS.find((preset) => preset.id === id)
  // Unreachable by type, and a real possibility at runtime if a stored id
  // survives a preset being removed. The default is the honest fallback.
  return found ?? THEME_PRESETS[0]
}

/** Asserts at module load that the two lists cannot drift apart. */
if (THEME_PRESETS.length !== THEME_PRESET_IDS.length) {
  throw new Error("THEME_PRESETS and THEME_PRESET_IDS disagree")
}
